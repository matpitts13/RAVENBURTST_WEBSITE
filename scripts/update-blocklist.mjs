// Refreshes the bundled list of disposable ("burner") email domains that
// signups are checked against, then reports any existing subscribers on them.
//   npm run list:update-blocklist              (refresh + report; changes no subscriber)
//   npm run list:update-blocklist -- --apply   (also blocks the subscribers it finds)
// Source: github.com/disposable-email-domains/disposable-email-domains (CC0).
// Redeploy the site afterwards so signups use the new list. Uses your
// `wrangler login` for the database.
import fs from "node:fs";
import { d1Read, d1Write } from "./d1.mjs";

const SOURCE = "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf";
const OUT = new URL("../functions/_lib/disposable-domains.js", import.meta.url);
const apply = process.argv.includes("--apply");

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`Couldn't fetch the list: HTTP ${res.status}`);
const domains = [...new Set(
  (await res.text()).split(/\r?\n/).map((l) => l.trim().toLowerCase()).filter((l) => l && !l.startsWith("#")),
)].sort();
const bad = domains.filter((d) => !/^[a-z0-9.-]+\.[a-z0-9-]+$/.test(d));
if (bad.length) throw new Error(`Unexpected lines in the list, not saved: ${bad.slice(0, 5).join(", ")}`);
if (domains.length < 1000) throw new Error(`Only ${domains.length} domains - looks wrong, not saved`);

fs.writeFileSync(
  OUT,
  `// Generated by scripts/update-blocklist.mjs - do not edit by hand.\n` +
    `// Disposable email domains from disposable-email-domains (CC0), ${new Date().toISOString().slice(0, 10)}.\n` +
    `// ${domains.length} domains.\n` +
    `export const DISPOSABLE_DOMAINS = new Set(\`\n${domains.join("\n")}\n\`.trim().split("\\n"));\n`,
);
console.log(`Saved ${domains.length} domains to functions/_lib/disposable-domains.js`);

// Existing subscribers on a listed domain (allowed_domains overrides still apply).
// Imported now: blocking.js needs the file written above.
const { BURNER_REASON, domainAndParents } = await import("../functions/_lib/blocking.js");
const list = new Set(domains);
let allowed, rows;
try {
  allowed = new Set((await d1Read("SELECT domain FROM allowed_domains")).map((r) => r.domain.toLowerCase()));
  rows = await d1Read("SELECT id, email, status FROM subscribers WHERE block_reason IS NULL");
} catch (err) {
  console.log(`Couldn't check existing subscribers (${err.message}). Is migrations/0003_blocking.sql applied, and wrangler logged in?`);
  process.exit(0);
}
const hits = rows.filter((r) => {
  const parents = domainAndParents(r.email.slice(r.email.lastIndexOf("@") + 1));
  return parents.some((d) => list.has(d)) && !parents.some((d) => allowed.has(d));
});
if (!hits.length) {
  console.log("No existing subscribers on a listed domain.");
} else {
  for (const r of hits) console.log(`  ${r.email} (${r.status})`);
  if (apply) {
    await d1Write(
      `UPDATE subscribers SET status = 'unsubscribed', unsubscribed_at = COALESCE(unsubscribed_at, datetime('now')),
         block_reason = '${BURNER_REASON}', blocked_at = datetime('now')
       WHERE block_reason IS NULL AND id IN (${hits.map((r) => Number(r.id)).join(", ")});`,
    );
    console.log(`Blocked ${hits.length} subscriber(s) as ${BURNER_REASON}.`);
  } else {
    console.log(`${hits.length} subscriber(s) on a listed domain. Run again with --apply to block them.`);
  }
}
